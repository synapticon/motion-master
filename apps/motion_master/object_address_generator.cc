std::string clientIdentifier(std::string_view cxxIdentifier) {
  const std::string_view name =
      cxxIdentifier.starts_with('k') ? cxxIdentifier.substr(1) : cxxIdentifier;
  const auto isUpper = [](char c) { return std::isupper(static_cast<unsigned char>(c)) != 0; };
  const auto isLower = [](char c) { return std::islower(static_cast<unsigned char>(c)) != 0; };
  const auto isDigit = [](char c) { return std::isdigit(static_cast<unsigned char>(c)) != 0; };
  std::string out;
  for (std::size_t i = 0; i < name.size(); ++i) {
    const char c = name[i];
    if (i > 0) {
      const char before = name[i - 1];
      const bool afterSmallOrDigit = isUpper(c) && (isLower(before) || isDigit(before));
      const bool endOfCapitals =
          isUpper(c) && isUpper(before) && i + 1 < name.size() && isLower(name[i + 1]);
      const bool digitAfterLetter = isDigit(c) && !isDigit(before);
      if (afterSmallOrDigit || endOfCapitals || digitAfterLetter) {
        out += '_';
      }
    }
    out += static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
  }
  return out;
}

std::string objectIdentifier(std::string_view objectName, std::string_view entryName,
                             uint8_t subindex, bool composite) {
  const auto pascal = [](std::string_view s) {
    std::string out;
    bool upper = true;
    for (char c : s) {
      if (std::isalnum(static_cast<unsigned char>(c)) != 0) {
        out += upper ? static_cast<char>(std::toupper(static_cast<unsigned char>(c))) : c;
        upper = false;
      } else {
        upper = true;
      }
    }
    return out;
  };

  std::string name = pascal(objectName);
  if (composite && subindex == 0) {
    // Subindex 0 of a composite is the entry count, not a value. Naming it after the object would
    // collide with whichever subindex repeats the object's own name.
    name += "Count";
  } else if (subindex != 0 && entryName != objectName) {
    name += pascal(entryName);
  }
  if (name.empty()) {
    name = "Object";
  }
  if (std::isdigit(static_cast<unsigned char>(name.front())) != 0) {
    name.insert(name.begin(), 'N');
  }
  return "k" + name;
}

std::expected<ObjectAddressGeneratorSummary, std::string> generateObjectAddresses(
    const std::string& esiPath, const std::string& outDir, const std::string& pythonPath,
    const std::string& typescriptPath) {
  auto file = mm::etg::parseEsiFile(esiPath);
  if (!file) {
    return std::unexpected(std::format("parsing {}: {}", esiPath, file.error()));
  }

  ObjectAddressGeneratorSummary summary;
  summary.warnings = file->warnings;

  // Merge every device's dictionary into one table keyed by address. That is sound only because the
  // vendor gives one address one meaning across the family — the same quantity, data type and unit
  // on a Node, a Circulo, a Circulo SMM and an Integro alike. For 0x1xxx and 0x6xxx the standards
  // require it; in the manufacturer-specific area (0x2xxx) nothing does, and it holds here because
  // those devices draw the bulk of their dictionary from one shared ESI module rather than from
  // four descriptions that happen to agree, so most of the union is the same text merged with
  // itself. Where two devices disagree on an entry's type the first wins and the difference is
  // reported rather than silently resolved; one index reused for a different quantity of the same
  // type is the case this cannot see, and would mean a header per device instead of one.
  std::map<uint32_t, EsiEntry> merged;
  for (const auto& device : file->devices) {
    auto table = mm::etg::buildDeviceEntries(*file, device, {});
    if (!table) {
      return std::unexpected(std::format("building '{}': {}", device.type, table.error()));
    }
    for (auto& warning : table->warnings) {
      summary.warnings.push_back(std::format("[{}] {}", device.type, warning));
    }
    for (auto& entry : table->entries) {
      auto [it, inserted] = merged.try_emplace(entry.key(), entry);
      if (!inserted && it->second.valueKind != entry.valueKind) {
        summary.warnings.push_back(
            std::format("0x{:04X}:{:02X} is {} on '{}' but {} elsewhere; keeping the first",
                        entry.index, entry.subindex, mm::etg::cxxTypeName(entry.valueKind),
                        device.type, mm::etg::cxxTypeName(it->second.valueKind)));
      }
    }
  }

  std::vector<Bucket> buckets{
      {"profile_device_objects.h",
       "mm::node::profile::objects",
       "CiA 301 communication area (0x1xxx) and the standard MDP objects",
       "Profile",
       {}},
      {"cia402_drive_objects.h",
       "mm::node::cia402::objects",
       "CiA 402 drive profile (0x6xxx)",
       "Cia402",
       {}},
      {"somanet_drive_objects.h",
       "mm::node::somanet::objects",
       "SOMANET vendor area (0x2xxx) and FSoE",
       "Somanet",
       {}},
  };
  for (const auto& [key, entry] : merged) {
    buckets[bucketFor(entry.index)].entries.push_back(&entry);
  }

  // Names are unique per file, not globally: the three namespaces are distinct, and a name that
  // appears in two of them is not a clash.
  std::vector<std::vector<Row>> rows(buckets.size());
  for (std::size_t b = 0; b < buckets.size(); ++b) {
    std::map<std::string, int> used;
    std::map<std::string, int> usedClient;
    for (const EsiEntry* entry : buckets[b].entries) {
      std::string id = objectIdentifier(entry->objectName, entry->entryName, entry->subindex,
                                        entry->objectCode != mm::etg::ObjectCode::Var);
      if (const int seen = used[id]++; seen > 0) {
        // Should not happen with the naming rule above, but a duplicate would be a compile error in
        // the generated file, so disambiguate deterministically and say so.
        summary.warnings.push_back(std::format("duplicate identifier {} at 0x{:04X}:{:02X}", id,
                                               entry->index, entry->subindex));
        id += std::format("At{:04X}{:02X}", entry->index, entry->subindex);
      }
      std::string clientName = clientIdentifier(id);
      if (const int seen = usedClient[clientName]++; seen > 0) {
        // Two C++ names that differ only where a capital starts a word give one client name.
        summary.warnings.push_back(std::format("duplicate client name {} at 0x{:04X}:{:02X}",
                                               clientName, entry->index, entry->subindex));
        clientName += std::format("_AT_{:04X}{:02X}", entry->index, entry->subindex);
      }

      std::string note = sanitiseComment(entry->objectName);
      if (entry->entryName != entry->objectName) {
        note += " / " + sanitiseComment(entry->entryName);
      }
      note += std::format(" — {}", mm::etg::accessModeName(entry->access.mode));
      if (!entry->unitSymbol.empty()) {
        note += ", " + sanitiseComment(entry->unitSymbol);
      }
      rows[b].push_back(Row{entry, std::move(id), std::move(clientName), std::move(note)});
    }
  }

  const std::string source = std::filesystem::path(esiPath).filename().string();
  for (std::size_t b = 0; b < buckets.size(); ++b) {
    const Bucket& bucket = buckets[b];
    std::string body;
    for (const Row& row : rows[b]) {
      body +=
          std::format("/// {}\ninline constexpr ObjectAddress<{}> {}{{0x{:04X}, 0x{:02X}}};\n\n",
                      row.note, mm::etg::cxxTypeName(row.entry->valueKind), row.cxxName,
                      row.entry->index, row.entry->subindex);
      ++summary.rows;
    }

    const std::filesystem::path path = std::filesystem::path(outDir) / bucket.fileName;
    auto written = writeFile(
        path,
        std::format(
            "// Generated by `motion-master generate-object-addresses` from {} — do not edit.\n"
            "// Regenerating is a two-step job: run that command, then `tools/format.sh` — "
            "clang-format\n"
            "// wraps the declarations that overrun 100 columns, and it does so "
            "context-sensitively\n"
            "// enough that reproducing its choices here would be guesswork.\n"
            "//\n"
            "// {} — {} addresses.\n"
            "//\n"
            "// Each constant carries an object's index, subindex and the C++ type its declared\n"
            "// ETG.1020 type maps to, so a call site cannot disagree with the object it names:\n"
            "//\n"
            "//     device.value(objects::kStatusword)        // std::optional<uint16_t>\n"
            "//     device.readValue(objects::kDeviceName)    // std::expected<std::string, ...>\n"
            "//\n"
            "// The union of every device in the ESI is emitted: which module is fitted is "
            "unknowable\n"
            "// offline, so an address that does not apply to the drive in front of you simply "
            "fails\n"
            "// to resolve at runtime, exactly as a hand-written index would. The trailing comment "
            "on\n"
            "// each line is the ESI's own name, access mode and unit — the unit especially, since "
            "a\n"
            "// temperature in milli-degrees looks exactly like one in degrees until a motor "
            "stops.\n"
            "//\n"
            "// One header serves the whole device family because SOMANET gives one address one\n"
            "// meaning across it: an index/subindex names the same quantity, with the same data "
            "type\n"
            "// and the same unit, on a Node, a Circulo, a Circulo SMM and an Integro alike. For\n"
            "// 0x1xxx and 0x6xxx the standards require that; in the manufacturer-specific area\n"
            "// (0x2xxx) nothing does — ETG.1000.6 reserves the range for the vendor and says "
            "nothing\n"
            "// about keeping it stable between devices — so it is a vendor convention, and it "
            "holds\n"
            "// here because those devices draw the bulk of their dictionary from one shared ESI\n"
            "// module (0x04020001, \"Default CiA402 object dictionary\") rather than from four\n"
            "// descriptions that happen to agree. Where two devices disagree on an address's "
            "type\n"
            "// the generator warns and keeps the first; one index reused for a different quantity "
            "of\n"
            "// the same type would merge silently, and would mean a header per device instead.\n"
            "\n#pragma once\n\n#include <cstdint>\n#include <string>\n#include <vector>\n\n"
            "#include \"node/device_parameter.h\"\n\nnamespace {} {{\n\n{}}}  // namespace {}\n",
            source, bucket.title, bucket.entries.size(), bucket.nameSpace, body, bucket.nameSpace));
    if (!written) {
      return std::unexpected(written.error());
    }
    summary.files.push_back(path.string());
  }

  if (auto written = writeFile(pythonPath, pythonModule(source, buckets, rows)); !written) {
    return std::unexpected(written.error());
  }
  summary.files.push_back(pythonPath);
  if (auto written = writeFile(typescriptPath, typescriptModule(source, buckets, rows)); !written) {
    return std::unexpected(written.error());
  }
  summary.files.push_back(typescriptPath);
  return summary;
}

