/// One output file: where its addresses go, and which entries belong in it.
struct Bucket {
  const char* fileName = nullptr;
  const char* nameSpace = nullptr;
  const char* title = nullptr;
  const char* className = nullptr;  ///< The class that holds these entries in the clients.
  std::vector<const EsiEntry*> entries;
};

/// One entry with its names, so the C++, Python and TypeScript files agree on every name.
struct Row {
  const EsiEntry* entry = nullptr;
  std::string cxxName;
  std::string clientName;
  std::string note;  ///< The ESI name, the access mode and the unit.
};

/// Which header an object belongs in, by index.
///
/// 0x1xxx is the CiA 301 communication area and 0x6xxx the CiA 402 drive profile, so both are
/// generic. Everything else here is either vendor-specific (0x2xxx) or a standard profile that only
/// shows up on these devices: the MDP objects (0xF000/0xF030/0xF050, ETG.5001 — the ones
/// reconcileDetectedModules already writes) are generic and go with the communication area, while
/// FSoE (0xE901, 0xF980) ships on the safety variant and goes with the vendor's.
std::size_t bucketFor(uint16_t index) {
  if (index >= 0x1000 && index <= 0x1FFF) {
    return 0;  // profile
  }
  if (index >= 0x6000 && index <= 0x6FFF) {
    return 1;  // cia402
  }
  if (index == 0xF000 || index == 0xF030 || index == 0xF050) {
    return 0;  // MDP — standard, so it belongs with the communication area
  }
  return 2;  // somanet: 0x2xxx-0x5xxx, FSoE, and anything else a vendor invents
}

/// Escapes a doc comment: entry names are vendor text and may contain anything.
std::string sanitiseComment(std::string_view text) {
  std::string out;
  out.reserve(text.size());
  for (char c : text) {
    // A '*' after a '/' would open a nested comment, so it goes the same way as whitespace.
    if (c == '\n' || c == '\r' || c == '\t' || (c == '*' && !out.empty() && out.back() == '/')) {
      out += ' ';
    } else {
      out += c;
    }
  }
  return out;
}

/// The Python type of a value, as the API sends it in JSON: every integer is an int.
std::string_view pythonTypeName(mm::etg::ValueKind kind) {
  using mm::etg::ValueKind;
  switch (kind) {
    case ValueKind::Real32:
    case ValueKind::Real64:
      return "float";
    case ValueKind::String:
      return "str";
    case ValueKind::Bytes:
      return "list[int]";
    default:
      return "int";
  }
}

/// The TypeScript type of a value, as the API sends it in JSON: every number is a number.
std::string_view typescriptTypeName(mm::etg::ValueKind kind) {
  using mm::etg::ValueKind;
  switch (kind) {
    case ValueKind::String:
      return "string";
    case ValueKind::Bytes:
      return "number[]";
    default:
      return "number";
  }
}

/// Escapes a JSDoc comment: a "*/" in vendor text would close it.
std::string escapeJsDoc(std::string_view text) {
  std::string out;
  for (std::size_t i = 0; i < text.size(); ++i) {
    out += text[i];
    if (text[i] == '*' && i + 1 < text.size() && text[i + 1] == '/') {
      out += ' ';
    }
  }
  return out;
}

/// The text both client files start with, as comment lines without the comment marker.
constexpr std::string_view kClientPreamble =
    "The objects of the SOMANET object dictionaries, as addresses: an index, a subindex and the\n"
    "type of the value. Profile holds the CiA 301 communication area (0x1xxx) and the standard "
    "MDP\n"
    "objects, Cia402 the CiA 402 drive profile (0x6xxx), and Somanet the SOMANET vendor area\n"
    "(0x2xxx) and FSoE. A name is the C++ name in libs/node/*_objects.h without its k, in\n"
    "capitals, so kStatusword is Cia402.STATUSWORD.\n"
    "\n"
    "The list is the union of every device in the ESI, so an address can name an object that the\n"
    "drive in front of you does not have. A read of it then fails. The comment on each address is\n"
    "the ESI name, the access mode and the unit.\n";

/// Prefixes each line of @p text with @p marker, and drops the space on an empty line.
std::string commentLines(std::string_view text, std::string_view marker) {
  std::string out;
  std::size_t start = 0;
  while (start < text.size()) {
    const std::size_t end = text.find('\n', start);
    const std::string_view line = text.substr(start, end - start);
    out += line.empty() ? std::string(marker) : std::format("{} {}", marker, line);
    out += '\n';
    start = end + 1;
  }
  return out;
}

std::string pythonModule(const std::string& source, const std::vector<Bucket>& buckets,
                         const std::vector<std::vector<Row>>& rows) {
  std::string out = std::format(
      "# Generated by `motion-master generate-object-addresses` from {}. Do not edit.\n"
      "\"\"\"{}\"\"\"\n\n"
      "from typing import Generic, NamedTuple, TypeVar\n\n"
      "_T = TypeVar(\"_T\")\n\n\n"
      "class ObjectAddress(NamedTuple, Generic[_T]):\n"
      "    \"\"\"An object of a device: its index and subindex. _T is the type of its value.\n\n"
      "    It unpacks to (index, subindex), so (1, *Cia402.STATUSWORD) is a monitoring parameter.\n"
      "    \"\"\"\n\n"
      "    index: int\n"
      "    subindex: int\n",
      source, kClientPreamble);
  for (std::size_t b = 0; b < buckets.size(); ++b) {
    out += std::format("\n\nclass {}:\n    \"\"\"{}. {} addresses.\"\"\"\n", buckets[b].className,
                       buckets[b].title, rows[b].size());
    for (const Row& row : rows[b]) {
      out +=
          std::format("\n    # {}\n    {}: ObjectAddress[{}] = ObjectAddress(0x{:04X}, 0x{:02X})\n",
                      row.note, row.clientName, pythonTypeName(row.entry->valueKind),
                      row.entry->index, row.entry->subindex);
    }
  }
  return out;
}

std::string typescriptModule(const std::string& source, const std::vector<Bucket>& buckets,
                             const std::vector<std::vector<Row>>& rows) {
  std::string out = std::format(
      "// Generated by `motion-master generate-object-addresses` from {}. Do not edit.\n"
      "//\n{}\n"
      "/** An object of a device: its index and subindex. `T` is the type of its value. */\n"
      "export interface ObjectAddress<T> {{\n"
      "  readonly index: number\n"
      "  readonly subindex: number\n"
      "  /** Never set. It carries `T`, so a read of this address returns the type of its value. "
      "*/\n"
      "  readonly valueType?: T\n"
      "}}\n\n"
      "function address<T>(index: number, subindex: number): ObjectAddress<T> {{\n"
      "  return {{ index, subindex }}\n"
      "}}\n",
      source, commentLines(kClientPreamble, "//"));
  for (std::size_t b = 0; b < buckets.size(); ++b) {
    out += std::format("\n/** {}. {} addresses. */\nexport const {} = {{\n", buckets[b].title,
                       rows[b].size(), buckets[b].className);
    for (const Row& row : rows[b]) {
      out += std::format("  /** {} */\n  {}: address<{}>(0x{:04X}, 0x{:02X}),\n",
                         escapeJsDoc(row.note), row.clientName,
                         typescriptTypeName(row.entry->valueKind), row.entry->index,
                         row.entry->subindex);
    }
    out += "} as const\n";
  }
  return out;
}

std::expected<void, std::string> writeFile(const std::filesystem::path& path,
                                           const std::string& text) {
  std::ofstream out(path, std::ios::binary | std::ios::trunc);
  if (!out) {
    return std::unexpected(std::format("cannot write {}", path.string()));
  }
  out << text;
  return {};
}

