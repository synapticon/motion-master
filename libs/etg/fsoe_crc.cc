/// Advances the CRC register by one input octet — one step of the Annex A reference loop.
constexpr uint16_t crcStep(uint16_t crc, uint8_t in) {
  const uint16_t w1 = static_cast<uint16_t>(kTable1[(crc >> 8) & 0xFF] ^ kTable2[in]);
  const auto crcLo = static_cast<uint8_t>(crc & 0xFF);
  const auto newHi = static_cast<uint8_t>(static_cast<uint8_t>(w1 >> 8) ^ crcLo);
  return static_cast<uint16_t>((static_cast<uint16_t>(newHi) << 8) | (w1 & 0xFF));
}

