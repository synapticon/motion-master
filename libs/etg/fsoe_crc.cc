uint16_t fsoeCrc(uint16_t recvCrc0, uint16_t connId, uint16_t seqNo, uint8_t command,
                 uint16_t index, std::span<const uint8_t> block, uint8_t blockLen) {
  if (blockLen != 1 && blockLen != 2) {
    return 0;
  }
  if (block.size() < blockLen) {
    return 0;
  }

  uint16_t crc = 0;
  crc = crcStep(crc, static_cast<uint8_t>(recvCrc0 & 0xFF));
  crc = crcStep(crc, static_cast<uint8_t>((recvCrc0 >> 8) & 0xFF));
  crc = crcStep(crc, static_cast<uint8_t>(connId & 0xFF));
  crc = crcStep(crc, static_cast<uint8_t>((connId >> 8) & 0xFF));
  crc = crcStep(crc, static_cast<uint8_t>(seqNo & 0xFF));
  crc = crcStep(crc, static_cast<uint8_t>((seqNo >> 8) & 0xFF));
  crc = crcStep(crc, command);
  // CRC_0 feeds in no index octets at all; every later block feeds in its index. Skipping this
  // distinction makes CRC_0 and CRC_1 collide whenever their SafeData happens to match.
  if (index > 0) {
    crc = crcStep(crc, static_cast<uint8_t>(index & 0xFF));
    crc = crcStep(crc, static_cast<uint8_t>((index >> 8) & 0xFF));
  }
  crc = crcStep(crc, block[0]);
  if (blockLen > 1) {
    crc = crcStep(crc, block[1]);
  }
  return crc;
}

std::span<const uint16_t> fsoeCrcTable1() { return kTable1; }

std::span<const uint16_t> fsoeCrcTable2() { return kTable2; }

